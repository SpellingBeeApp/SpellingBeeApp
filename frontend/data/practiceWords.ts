export const ALL_PRACTICE_WORDS: Record<string, PracticeWord> =
  Object.values(PRACTICE_GRADES)
    .flatMap((byDifficulty) => Object.values(byDifficulty))
    .flat()
    .reduce<Record<string, PracticeWord>>((lookup, practiceWord) => {
      lookup[practiceWord.word] = practiceWord;
      return lookup;
    }, {});

/**
 * Looks up which grade/difficulty a word belongs to, so an attempt can be
 * logged correctly even in Review Mode, where the quiz mixes words from
 * different grades and difficulties.
 */
export const WORD_LOCATION: Record<
  string,
  { grade: number; difficulty: Difficulty }
> = Object.entries(PRACTICE_GRADES).reduce<
  Record<string, { grade: number; difficulty: Difficulty }>
>((lookup, [gradeKey, byDifficulty]) => {
  const grade = Number(gradeKey);
  Object.entries(byDifficulty).forEach(([difficulty, words]) => {
    words.forEach((practiceWord) => {
      lookup[practiceWord.word] = { grade, difficulty: difficulty as Difficulty };
    });
  });
  return lookup;
}, {});

/**
 * Groups every word by each spelling-pattern tag it carries, so "Practice a
 * Weak Spot" mode can pull a pool of words for a chosen category regardless
 * of grade or difficulty. A word with multiple tags appears in each group.
 */
export const WORDS_BY_PATTERN: Record<SpellingPattern, PracticeWord[]> =
  Object.values(ALL_PRACTICE_WORDS).reduce<Record<string, PracticeWord[]>>(
    (groups, practiceWord) => {
      (practiceWord.patterns ?? []).forEach((pattern) => {
        groups[pattern] = groups[pattern] ?? [];
        groups[pattern].push(practiceWord);
      });
      return groups;
    },
    {},
  ) as Record<SpellingPattern, PracticeWord[]>;
